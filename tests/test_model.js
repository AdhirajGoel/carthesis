'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const M=require('../web/model.js');
const demo=M.validate(JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../examples/comparison.json'),'utf8')));
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-6,`${a} != ${b}`);
close(M.minimum(12000,0,12),1000);
const loan=M.loan(12000,12,12,null,6);
assert.equal(loan.months,12);assert.ok(loan.balance>0);assert.ok(loan.interest<loan.totalInterest);
close(loan.balance,loan.balances[6]);
const early=M.loan(12000,12,12,2000,6);assert.ok(early.totalInterest<loan.totalInterest);
assert.throws(()=>M.loan(12000,12,12,10,6),/contractual/);
close(M.growth(1.5,10),1.55);
const p={...M.defaults,years:1,tax:0,fees:0,daily:0,ins:0,reg:0,infl:0,down:0,term:60};
const vehicle={...demo.vehicles[0],price:12000,apr:12,maint:0,r5:0.5,r10:0.2};
const c=M.compute(vehicle,p);close(c.net,12000+c.financing.interest-c.resale);assert.equal(c.perMile,null);
assert.ok(c.interest<c.financing.totalInterest);
const pair=M.hybrids(demo.vehicles,demo.assumptions)[0];
close(pair.netSavings,M.compute(pair.gas,demo.assumptions).net-M.compute(pair.hybrid,demo.assumptions).net);
assert.ok(pair.netSavings<0,'Demo hybrid should not repay its premium at these assumptions');
assert.ok(M.compute(demo.vehicles[2],demo.assumptions).net>M.compute(demo.vehicles[0],demo.assumptions).net,'Demo used car should cost more to own despite lower asking price');
const included=['purchase','fuel'];close(M.compute(vehicle,p,included).net,12000);
for(const bad of [{...demo,vehicles:[]},{...demo,vehicles:[{...vehicle,mpg:0}]},{...demo,assumptions:{...p,years:0}},{...demo,vehicles:[{...vehicle,apr:NaN}]}])assert.throws(()=>M.validate(bad));
const script=fs.readFileSync(require('node:path').join(__dirname,'../web/demo.js'),'utf8');
assert.deepEqual(JSON.parse(script.slice('const DEMO = '.length).trim().replace(/;$/,'')),JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../examples/comparison.json'),'utf8')));
console.log('Ownership, financing, hybrid, input validation and demo consistency checks passed');
